"""Explicitly trusted native results, with index-only diagnostic projections."""

import io
import pickle
from pathlib import Path
from types import SimpleNamespace

import numpy as np
from chaco.api import ArrayPlotData

from pybert.results import PyBertData
from pybert.web.archive import MAX_ARRAY_BYTES, atomic_write, json_bytes, sha256

LOSS = ["complete inputs/resources/run identity", "physical axes/windows/clocks", "Rx FFE full results",
        "eyes/jitter/bathtubs", "raw complex frequency responses", "scalar performance/logs/subtasks"]


def load_legacy(content, directory, trusted=False):
    if trusted is not True:
        raise ValueError("Legacy pickle requires explicit selection of a trusted local file; it can execute code.")
    try:
        result = pickle.loads(content)  # noqa: S301 - explicit trusted local-user opt-in only
    except Exception as err:
        raise ValueError(f"Unable to read trusted native results: {err}") from err
    if type(result) is not PyBertData or type(getattr(result, "the_data", None)) is not ArrayPlotData:
        raise ValueError("Expected known PyBertData/ArrayPlotData containers.")
    data = result.the_data.arrays
    if set(data) - set(PyBertData._item_names):
        raise ValueError("Unknown native results fields; record not published.")
    arrays, datasets, plots, absent = {}, {}, {}, {}
    version = str(getattr(result, "version", "unknown"))
    for field in PyBertData._item_names:
        value = data.get(field)
        if value is None or (isinstance(value, np.ndarray) and value.shape == () and value.dtype.kind == "O" and value.item() is None):
            absent[field] = "not generated by native plotdata producer"
            continue
        if not isinstance(value, np.ndarray) or value.dtype.kind not in "biuf" or value.ndim != 1 or not len(value) or not np.isfinite(value).all():
            raise ValueError(f"{field}: expected a finite 1-D native display array.")
        axis = f"legacy.index.{field}"
        frequency = field.endswith("_H")
        xunit = "frequency-bin index" if frequency else "sample index"
        unit = ("dB" if frequency else "V/sample" if field.endswith("_h") else "V") if version == "11.1.0" else "unknown legacy unit"
        arrays[field], arrays[axis] = value, np.arange(len(value))
        metadata = dict(producer="native update_results plotdata", point=field.split("_")[0],
                        kind="legacy diagnostic display", window={"availability": "unknown; absent in legacy"},
                        clock_basis="unknown; absent in legacy", display_noise="unknown", availability="available")
        datasets[field] = dict(metadata, field=field, dtype=str(value.dtype), shape=list(value.shape), unit=unit, axis=axis)
        datasets[axis] = dict(metadata, field=axis, dtype="int64", shape=[len(value)], unit=xunit, axis=None)
        plots[field] = {"title": f"{field} · legacy index diagnostic (physical axis unavailable)",
                        "traces": [{"x": axis, "y": field, "name": field, "xunit": xunit, "yunit": unit}],
                        "metadata": {"physical_comparison": "unavailable; no original axes/input evidence", "frequency_values": "already display dB; no second conversion" if frequency and version == "11.1.0" else "native stored values"}}
    if sum(a.nbytes for a in arrays.values()) > MAX_ARRAY_BYTES or not plots:
        raise ValueError("Empty legacy data or numerical byte budget exceeded.")
    run = {"schema_version": 1, "raw_schema_version": 4, "run_id": f"legacy-{sha256(content)}", "status": "succeeded",
           "legacy": {"version": version, "date_created": str(getattr(result, "date_created", "unknown")), "absent": absent,
                      "losses": LOSS, "physical_axes": "unavailable", "trusted_user_selected": True},
           "requested_input": {}, "effective_input": {}, "input_hash": "unknown", "summary": {}, "window": {"availability": "unknown"},
           "datasets": datasets, "plots": plots, "warnings": ["Legacy subset only; original run/config/axes unknown."], "logs": []}
    buffer = io.BytesIO()
    np.savez_compressed(buffer, **arrays)
    directory = Path(directory)
    atomic_write(directory / "arrays.npz", buffer.getvalue())
    atomic_write(directory / "manifest.json", json_bytes(run))
    atomic_write(directory / "legacy.pybert_data", content)
    return run, sum(a.nbytes for a in arrays.values())


def legacy_report(directory):
    from pybert.web.archive import read_json

    run = read_json(Path(directory, "manifest.json").read_bytes())
    fields, absent = {}, {}
    for field in PyBertData._item_names:
        key = field if run.get("legacy") or not field.endswith("_H") else f"display.{field}.y"
        # tx_out is not rx_in: the current native producer never creates this plotdata item.
        if key not in run["datasets"]:
            absent[field] = "not generated as a native plotdata item; no zero/relabelled waveform substituted"
        else:
            fields[field] = {"dataset": key, "metadata": run["datasets"][key]}
    with np.load(Path(directory, "arrays.npz"), allow_pickle=False) as arrays:
        axes = {key: {"metadata": run["datasets"].get(value["metadata"].get("axis")),
                      "values": arrays[value["metadata"]["axis"]].tolist() if value["metadata"].get("axis") in arrays else None}
                for key, value in fields.items()}
    full_archive_available = not bool(run.get("legacy"))
    return {"source_run_id": run["run_id"], "available": not absent, "fields": fields, "absent": absent,
            "losses": LOSS, "sidecar_schema": 1, "axes": axes,
            "native_producer_version": run.get("legacy", {}).get("version", run.get("packages", {}).get("pipbert", "unknown")),
            "native_producer_date": run.get("legacy", {}).get("date_created", str(run.get("lifecycle", {}).get("created_at", "unknown"))),
            "full_archive_available": full_archive_available,
            "full_archive_reason": "" if full_archive_available else "Legacy缺少完整原输入和物理轴，无法保存完整Web archive。",
            "recommendation": "Save full Web archive for lossless results." if full_archive_available else "Legacy缺少完整原输入和物理轴，无法保存完整Web archive；请保留原文件，可导出数据齐全的原生子集或独立sidecar。"}


def export_legacy(directory, destination):
    """Use the native 23-item constructor only when every producer item exists."""
    report = legacy_report(directory)
    if not report["available"]:
        raise ValueError(f"Native Save Results unavailable: {report['absent']}. {report['recommendation']}")
    with np.load(Path(directory, "arrays.npz"), allow_pickle=False) as arrays:
        data = ArrayPlotData(**{field: arrays[row["dataset"]] for field, row in report["fields"].items()})
    result = PyBertData(SimpleNamespace(plotdata=data), report["native_producer_date"], report["native_producer_version"])
    atomic_write(destination, pickle.dumps(result))
    atomic_write(Path(str(destination) + ".json"), json_bytes(report))
    return report
